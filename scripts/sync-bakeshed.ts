/**
 * Pulls the full Bakeshed catalogue (WooCommerce Store API) into content/catalogue.generated.ts
 * and downloads 400px WebP thumbnails into /public/catalogue. Prices are deliberately NOT stored.
 *   npm run sync:bakeshed
 * Behind a proxy, HTTPS_PROXY is honoured automatically.
 */
import fs from "node:fs";
import sharp from "sharp";
import { EnvHttpProxyAgent, fetch as ufetch, setGlobalDispatcher } from "undici";
import { products } from "../content/products";

if (process.env.HTTPS_PROXY || process.env.https_proxy) setGlobalDispatcher(new EnvHttpProxyAgent());

const API = "https://bakeshed.rw/wp-json/wc/store/v1/products";
const PARTNERS: [RegExp, string][] = [
  [/probake/i, "Niacet"],
  [/dairyland/i, "Dairyland"],
  [/magest/i, "Magest"],
  [/bakerdream/i, "Bakerdream"],
];
/** Shop items that share a concept product (other sizes of the same product). */
const ALIASES: [RegExp, string][] = [
  [/^round-cakebase-/, "round-cake-base"],
  [/^cake-box-/, "cake-box"],
  [/^red-cherries-/, "red-cherries"],
  [/^bakeshed-icing-sugar/, "icing-sugar"],
  [/^bakeshed-red-velvet/, "red-velvet"],
  [/^bakeshed-whipping-cream/, "whipping-cream-whip-s"],
  [/^bakeshed-oil-muffin-vanilla/, "oil-muffin-vanilla"],
];

const decode = (s: string) =>
  s.replace(/&#(\d+);/g, (_, n) => String.fromCharCode(+n)).replace(/&amp;/g, "&").replace(/&#8243;/g, "″").replace(/&quot;/g, '"');
const strip = (s: string) => decode(s.replace(/<[^>]+>/g, " ")).replace(/\s+/g, " ").trim();

type WC = { slug: string; name: string; permalink: string; short_description: string; categories: { slug: string }[]; images: { src: string; thumbnail: string }[] };

(async () => {
  const all: WC[] = [];
  for (let page = 1; page < 10; page++) {
    const r = await ufetch(`${API}?per_page=100&page=${page}`);
    if (!r.ok) throw new Error(`Store API ${r.status}`);
    const batch = (await r.json()) as WC[];
    all.push(...batch);
    if (batch.length < 100) break;
  }
  fs.mkdirSync("public/catalogue", { recursive: true });
  const byUrl = new Map(products.map((p) => [p.shopUrl, p.slug]));
  const out = [];
  for (const p of all) {
    const name = decode(p.name);
    const partner = PARTNERS.find(([re]) => re.test(name))?.[1];
    const conceptSlug = byUrl.get(p.permalink) ?? ALIASES.find(([re]) => re.test(p.slug))?.[1];
    const file = `/catalogue/${p.slug}.webp`;
    const src = p.images[0]?.thumbnail || p.images[0]?.src;
    if (src && !fs.existsSync(`public${file}`)) {
      const buf = Buffer.from(await (await ufetch(src)).arrayBuffer());
      await sharp(buf).resize(400, 400, { fit: "contain", background: "#ffffff" }).flatten({ background: "#ffffff" }).webp({ quality: 74 }).toFile(`public${file}`);
    }
    out.push({
      slug: p.slug,
      name,
      category: p.categories[0]?.slug,
      pack: strip(p.short_description) || undefined,
      image: src ? file : undefined,
      shopUrl: p.permalink,
      brand: /bakeshed/i.test(name) ? "bakeshed" : partner ? "partner" : "unbranded",
      partner,
      conceptSlug,
    });
  }
  out.sort((a, b) => a.name.localeCompare(b.name));
  fs.writeFileSync(
    "content/catalogue.generated.ts",
    `// Generated by scripts/sync-bakeshed.ts on ${new Date().toISOString().slice(0, 10)} from bakeshed.rw. Do not edit; re-run the script.\n` +
      `import type { CatalogueItem } from "./types";\n\nexport const catalogue: CatalogueItem[] = ${JSON.stringify(out, null, 2)};\n`,
  );
  const counts = out.reduce<Record<string, number>>((m, x) => ((m[x.category] = (m[x.category] ?? 0) + 1), m), {});
  console.log(`✓ ${out.length} products, ${out.filter((x) => x.conceptSlug).length} linked to concept packs, ${out.filter((x) => x.brand === "partner").length} partner brands`);
  console.log(counts);
})();
