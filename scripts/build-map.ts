/**
 * Builds content/map.generated.ts: SVG paths for Kenya, Uganda, Rwanda and neighbours
 * (Natural Earth 1:50m via world-atlas) and projected hub positions.
 *   npx tsx scripts/build-map.ts
 */
import fs from "node:fs";
import { geoMercator, geoPath } from "d3-geo";
import { feature } from "topojson-client";
import world from "world-atlas/countries-50m.json" with { type: "json" };

const W = 600, H = 560;
const focus: Record<string, string> = { "404": "KE", "800": "UG", "646": "RW" };
const context = new Set(["834", "180", "108", "728", "231", "706", "178", "140"]);

const fc = feature(world as any, (world as any).objects.countries) as any;
const features = fc.features.filter((f: any) => focus[f.id] || context.has(f.id));
const frame = { type: "Feature", geometry: { type: "MultiPoint", coordinates: [[28.6, 5.2], [42.2, -5.2]] } } as any;
const proj = geoMercator().fitExtent([[10, 10], [W - 10, H - 10]], frame);
const path = geoPath(proj);
const countries = features.map((f: any) => ({
  id: focus[f.id] ?? f.id,
  name: f.properties.name,
  focus: !!focus[f.id],
  d: path(f)!.replace(/(\d+\.\d{1})\d+/g, "$1"),
}));
const hub = (lon: number, lat: number) => proj([lon, lat])!.map((v) => Math.round(v * 10) / 10);
const hubs = {
  KE: hub(36.88, -1.32), // Nairobi, ICD Road off Mombasa Road
  UG: hub(32.68, 0.36), // Namanve Industrial Park, Kampala
  RW: hub(30.13, -1.93), // Kigali Special Economic Zone, Gasabo
};
const out = `// Generated by scripts/build-map.ts from Natural Earth 1:50m (public domain). Do not edit.
export const mapViewBox = { w: ${W}, h: ${H} };
export const mapCountries = ${JSON.stringify(countries)} as { id: string; name: string; focus: boolean; d: string }[];
export const mapHubs = ${JSON.stringify(hubs)} as Record<"KE" | "UG" | "RW", [number, number]>;
`;
fs.writeFileSync("content/map.generated.ts", out);
console.log(countries.map((c: any) => `${c.id}:${c.name}`).join(", "), hubs, `${(out.length / 1024).toFixed(0)} KB`);
