/**
 * Content model for the Maya E.A. Limited site and the BRANDED packaging proposal.
 * Every fact in /content must come from mayaealtd.com, bakeshed.rw or the client brief.
 * Anything not verified is written as a Confirm placeholder (see `confirm()` in ./confirm.ts).
 */

export type CategorySlug =
  | "baking-papers"
  | "bread-improvers"
  | "bread-premixes"
  | "cake-bases"
  | "cake-boxes"
  | "cake-premixes"
  | "chocolates"
  | "fruits"
  | "general-class"
  | "liquid-flavours"
  | "piping-gels"
  | "preservatives"
  | "seeds"
  | "vermicelli";

/** Shelf grouping used on the packaging page. */
export type CategoryFamily = "bread" | "cake" | "packaging";

/** 3D / dieline formats. Each maps to one simple-geometry model in the 3D viewer. */
export type PackFormat = "sack" | "box" | "pouch" | "tub" | "bottle" | "sleeve";

export type IconName =
  | "loaf-rise"
  | "wheat"
  | "cake-slice"
  | "cake-board"
  | "cake-box"
  | "choc-bar"
  | "cherries"
  | "bowl-whisk"
  | "droplet"
  | "piping-bag"
  | "shield"
  | "seeds"
  | "sprinkles"
  | "paper-case";

export interface Category {
  slug: CategorySlug;
  name: string;
  /** Two-letter code printed on every pack so colour is never the only cue. */
  code: string;
  /** 01–14, printed with the code. */
  index: number;
  family: CategoryFamily;
  /** Category colour (pack colour field). */
  colour: string;
  /** Text colour used on the colour field; chosen for WCAG AA contrast. */
  ink: "#FFFFFF" | "#0D2036";
  icon: IconName;
  /** Short "what it does" line, taken from Maya's Products page copy. */
  whatItDoes: string;
  /** Longer description, verbatim from mayaealtd.com/products. */
  description: string;
  /** Example items listed on mayaealtd.com/products. */
  examples: string[];
  /** Product count on bakeshed.rw (refresh with `npm run sync:bakeshed`). */
  shopCount: number;
  shopUrl: string;
  defaultFormat: PackFormat;
}

/** Is the product Maya's own label? Concept packs are only made for own-label products. */
export type OwnLabelStatus =
  /** Sold under the Bakeshed name on bakeshed.rw. */
  | "own-label"
  /** Unbranded on the shop; shown as a concept only until Maya confirms it is own-label. */
  | "confirm";

export interface PackSize {
  /** Text printed on the pack, e.g. "10 kg". */
  label: string;
  /** Unit inside the outer pack, e.g. "1 kg × 10". Optional. */
  carton?: string;
  /** Raw text from the shop, kept for traceability. */
  shopText: string;
  format: PackFormat;
}

export interface Dosage {
  /** Percent of total flour weight. Only verified figures. */
  minPercent: number;
  maxPercent: number;
  source: string;
}

export interface Product {
  slug: string;
  category: CategorySlug;
  /** Name as printed on the concept pack. */
  name: string;
  /** Product-type line under the name (e.g. "Bread improver"). */
  descriptor: string;
  /** Exact name on bakeshed.rw. */
  shopName: string;
  shopUrl: string;
  ownLabel: OwnLabelStatus;
  /** Overrides the category line when Maya's own pack makes a specific claim. */
  whatItDoes?: string;
  /** Claims printed on Maya's current pack (verified from the pack photo). */
  packClaims?: string[];
  packSizes: PackSize[];
  dosage?: Dosage;
  /** Verified usage line from Maya's current pack. */
  usage?: string;
  /** Verified storage line, or undefined → Confirm placeholder on the back panel. */
  storage?: string;
  /** Verified ingredients/allergens (from Maya's current pack photo). */
  ingredients?: string;
  allergens?: string;
  madeIn?: string;
  /** Current pack photo on bakeshed.rw (used for the before/after slider). */
  currentPhoto: string;
  /** Notes on the current photo, e.g. reused image. */
  photoNote?: string;
  /** Feature this product in the hero line-up and shelf. */
  featured?: boolean;
}

export interface Office {
  country: "Kenya" | "Uganda" | "Rwanda";
  countryCode: "KE" | "UG" | "RW";
  entity: string;
  role: string;
  addressLines: string[];
  phones: { label: string; number: string }[];
  whatsapp: string[];
  emails: string[];
  website?: string;
  shopUrl?: string;
}

/** One product on bakeshed.rw (generated by scripts/sync-bakeshed.ts). No prices by design. */
export interface CatalogueItem {
  slug: string;
  name: string;
  category: CategorySlug;
  /** Pack line from the shop, e.g. "1×10 Kgs". */
  pack?: string;
  image?: string;
  shopUrl: string;
  brand: "bakeshed" | "partner" | "unbranded";
  partner?: string;
  /** Slug in content/products.ts when a concept pack exists. */
  conceptSlug?: string;
}
